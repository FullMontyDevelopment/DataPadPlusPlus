import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import ts from 'typescript'
import { build } from 'esbuild'

const root = fileURLToPath(new URL('../', import.meta.url))
const source = path.join(root, 'packages/shared-types/src/workspace.ts')
const program = ts.createProgram([source], { strict: true, target: ts.ScriptTarget.ES2022, moduleResolution: ts.ModuleResolutionKind.Bundler, module: ts.ModuleKind.ESNext })
const checker = program.getTypeChecker()
const declarations = program.getSourceFile(source)
function schema(type, depth = 0) {
  if (depth > 35) throw new Error('Recursive compiler contract is unsupported')
  const flags = type.flags
  if (type.isUnion()) return { anyOf: type.types.filter(t => !(t.flags & ts.TypeFlags.Undefined)).map(t => schema(t, depth + 1)) }
  if (flags & ts.TypeFlags.StringLiteral || flags & ts.TypeFlags.NumberLiteral) return { const: type.value }
  if (flags & ts.TypeFlags.BooleanLiteral) return { const: type.intrinsicName === 'true' }
  if (flags & ts.TypeFlags.String) return { type: 'string' }
  if (flags & ts.TypeFlags.Number) return { type: 'number' }
  if (flags & ts.TypeFlags.Boolean) return { type: 'boolean' }
  if (flags & ts.TypeFlags.Null) return { type: 'null' }
  if (flags & (ts.TypeFlags.Any | ts.TypeFlags.Unknown)) return {}
  if (checker.isArrayType(type)) return { type: 'array', items: schema(checker.getTypeArguments(type)[0], depth + 1) }
  const properties = {}, required = []
  for (const property of type.getProperties()) {
    properties[property.name] = schema(checker.getTypeOfSymbolAtLocation(property, property.valueDeclaration ?? declarations), depth + 1)
    if (!(property.flags & ts.SymbolFlags.Optional)) required.push(property.name)
  }
  const index = type.getStringIndexType()
  return { type: 'object', properties, required, additionalProperties: index ? schema(index, depth + 1) : false }
}
const schemas = {}
for (const declaration of declarations.statements) {
  if (['QueryBuilderState', 'DatastoreTestSuiteDefinition'].includes(declaration.name?.text)) schemas[declaration.name.text] = schema(checker.getTypeAtLocation(declaration))
}
const schemaText = `// Generated by tools/build-query-compiler.mjs. Do not edit.\nimport type { Schema } from './schema-validation'\nexport const schemas: Record<'QueryBuilderState' | 'DatastoreTestSuiteDefinition', Schema> = ${JSON.stringify(schemas)}\n`
const schemaPath = path.join(root, 'packages/query-compiler/src/schemas.ts')
const result = await build({
  absWorkingDir: root, entryPoints: ['packages/query-compiler/src/index.ts'], bundle: true,
  platform: 'neutral', format: 'iife', globalName: 'DataPadQueryCompiler', write: false,
  target: 'es2022', legalComments: 'none',
  plugins: [{ name: 'generated-schema', setup(builder) {
    builder.onResolve({ filter: /^\.\/schemas$/ }, () => ({ path: schemaPath, namespace: 'schema' }))
    builder.onLoad({ filter: /.*/, namespace: 'schema' }, () => ({ contents: schemaText, loader: 'ts' }))
  } }],
})
const bundlePath = path.join(root, 'apps/desktop/src-tauri/src/app/runtime/query_compiler.js')
const outputs = [[schemaPath, schemaText], [bundlePath, '// Generated by tools/build-query-compiler.mjs. Do not edit.\n' + result.outputFiles[0].text]]
for (const [file, text] of outputs) {
  if (process.argv.includes('--check')) {
    if ((await readFile(file, 'utf8')).replaceAll('\r\n', '\n') !== text) throw new Error('Shared query compiler is stale. Run npm run query-compiler:generate.')
  } else await writeFile(file, text)
}
console.log(`Shared query compiler ${process.argv.includes('--check') ? 'verified' : 'generated'}.`)
